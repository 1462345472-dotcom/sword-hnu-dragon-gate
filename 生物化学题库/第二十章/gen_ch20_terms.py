# -*- coding: utf-8 -*-
"""第二十章 磷酸戊糖途径 名词解释 terms.json(18个,定义30-80字)"""
import json, sys, os
sys.stdout.reconfigure(encoding='utf-8')

T = []

def add(term, definition):
    T.append({
        "id": len(T) + 1,
        "term": term,
        "name": term,
        "definition": definition,
        "chapter": "biochem_20",
    })

add("磷酸戊糖途径(PPP)",
    "从6-磷酸葡萄糖开始,不经糖酵解和柠檬酸循环,直接脱氢脱羧为磷酸戊糖,再经重排又生成6-磷酸葡萄糖的过程,发生于细胞质溶胶,产生NADPH和5-磷酸核糖。")

add("己糖磷酸支路(HMP)",
    "磷酸戊糖途径的别名,又称6-磷酸葡萄糖酸途径;葡萄糖经6-磷酸葡萄糖脱氢脱羧生成磷酸戊糖,再经基团转移重排,主要产生NADPH和5-磷酸核糖。")

add("氧化脱羧阶段",
    "磷酸戊糖途径的第一阶段:6-磷酸葡萄糖经脱氢、水解、氧化脱羧,生成5-磷酸核酮糖并释放CO2,以NADP+为受氢体产生NADPH,此阶段不可逆。")

add("非氧化分子重排阶段",
    "磷酸戊糖途径的第二阶段:5-磷酸核酮糖经异构化、差向异构和基团转移,生成3-磷酸甘油醛和6-磷酸果糖,净结果3分子五碳糖变为2分子六碳糖和1分子三碳糖。")

add("6-磷酸葡萄糖脱氢酶",
    "磷酸戊糖途径的限速酶,催化6-磷酸葡萄糖脱氢生成6-磷酸葡萄糖酸-δ-内酯,以NADP+为辅酶;其反应实质上不可逆,受NADP+/NADPH比例调控。")

add("6-磷酸葡萄糖酸内酯酶",
    "磷酸戊糖途径氧化阶段的专一性酶,催化6-磷酸葡萄糖酸-δ-内酯水解为6-磷酸葡萄糖酸,消耗1分子H2O,属水解反应,不涉及氧化还原。")

add("6-磷酸葡萄糖酸脱氢酶",
    "磷酸戊糖途径氧化阶段第三步的酶,专一以NADP+为电子受体,催化6-磷酸葡萄糖酸氧化脱羧生成5-磷酸核酮糖和CO2,反应包括氧化和脱羧,需Mg2+。")

add("5-磷酸核酮糖",
    "磷酸戊糖途径氧化脱羧阶段的产物,由6-磷酸葡萄糖酸脱氢酶催化生成;是非氧化阶段的起点,可异构化为5-磷酸核糖,或差向异构为5-磷酸木酮糖。")

add("5-磷酸木酮糖",
    "磷酸戊糖途径非氧化阶段的中间产物,由5-磷酸核酮糖差向异构生成,作为转酮醇酶的底物,提供二碳酮醇基单位,参与7-磷酸景天庚酮糖和3-磷酸甘油醛的生成。")

add("5-磷酸核糖",
    "磷酸戊糖途径是体内产生5-磷酸核糖的唯一途径,后者由5-磷酸核酮糖异构化生成,是核苷酸及脱氧核糖合成的前体,也是组氨酸合成的原料。")

add("转酮醇酶",
    "磷酸戊糖途径非氧化阶段催化二碳(酮醇基)单位转移的酶,需TPP和Mg2+;催化5-磷酸木酮糖与5-磷酸核糖生成7-磷酸景天庚酮糖和3-磷酸甘油醛。")

add("转醛醇酶",
    "非氧化阶段催化三碳单位转移的酶,不需TPP;催化7-磷酸景天庚酮糖与3-磷酸甘油醛反应,生成6-磷酸果糖和4-磷酸赤藓糖,是4-磷酸赤藓糖的主要来源。")

add("7-磷酸景天庚酮糖",
    "磷酸戊糖途径非氧化阶段的七碳糖中间产物,由转酮醇反应(5-磷酸木酮糖+5-磷酸核糖)生成;作为转醛醇酶的酮糖供体提供三碳单位,生成6-磷酸果糖和4-磷酸赤藓糖。")

add("4-磷酸赤藓糖",
    "磷酸戊糖途径非氧化阶段产生的四碳糖磷酸酯,由转醛醇反应生成;是芳香族氨基酸和维生素B6生物合成的前体,体现磷酸戊糖途径与氨基酸代谢的联系。")

add("还原性生物合成",
    "指利用NADPH提供还原力的生物合成,如脂肪酸、胆固醇、核苷酸和神经递质的合成;磷酸戊糖途径产生的NADPH是这类合成的主要还原力来源。")

add("吡啶核苷酸转氢酶",
    "催化NADPH与NAD+之间氢转移,使NADPH将氢转移给NAD+生成NADH;因NADPH不能直接进入呼吸链,经此酶转化后NADH才可进入呼吸链产能。")

add("NADPH氧化酶",
    "位于巨噬细胞等吞噬细胞膜上的酶,催化NADPH将电子转移给O2形成超氧阴离子;超氧阴离子具有杀菌活性,是机体免疫防御、杀死入侵微生物的重要机制。")

add("谷胱甘肽还原酶",
    "以NADPH为辅酶,催化氧化型谷胱甘肽(GSSG)还原为还原型谷胱甘肽(GSH);GSH以-SH基团维持红细胞蛋白质结构完整并保护脂膜免受氧化损伤。")

# 校验 30-80 字
ok = True
for t in T:
    n = len(t["definition"])
    flag = 'OK' if 30 <= n <= 80 else '超出!'
    if not (30 <= n <= 80):
        ok = False
    print(f'{t["term"]}: {n}字 {flag}')
assert ok, '存在超字数定义'

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'terms.json')
with open(path, 'w', encoding='utf-8') as f:
    json.dump(T, f, ensure_ascii=False, indent=1)
print(f'terms: {len(T)} 个已落盘 -> {path}')
