"""合并 batch1-4 → questions.json;生成 terms.json"""
import json, sys, importlib
sys.stdout.reconfigure(encoding='utf-8')

qs = []
for i in range(1, 5):
    mod = importlib.import_module(f'batch{i}')
    qs.extend(mod.Q)
    print(f'batch{i}: {len(mod.Q)} 题')

# 分配 id
for idx, q in enumerate(qs, 1):
    q['id'] = idx

# 校验 topic 不为空、id 连续
topics = set()
for q in qs:
    assert q.get('topic'), f"缺topic: {q['question'][:30]}"
    topics.add(q['topic'])

with open('生物化学题库/第二十六章/questions.json', 'w', encoding='utf-8') as f:
    json.dump(qs, f, ensure_ascii=False, indent=1)

from collections import Counter
print('总题量:', len(qs))
print('题型分布:', dict(Counter(q['type'] for q in qs)))
print('topic数:', len(topics))

