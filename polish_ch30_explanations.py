def main():
    qs = json.load(open(PATH, encoding='utf-8'))
    changed = 0
    for q in qs:
        if q.get('type') != 'short' or q.get('id') not in NEW_EXPLANATIONS:
            continue
        qid = q['id']
        old = q.get('explanation', '')
        new = NEW_EXPLANATIONS[qid]
        if old.strip() == new.strip():
            continue
        # 安全断言:旧解析确实与答案逐字重复(剥离"参考答案:"前缀后)
        import re
        def norm(s):
            s = s.strip()
            m = re.match(r'^(?:参考答案|参考解答|答案|解析|【参考答案】)\s*[:：]\s*', s)
            if m:
                s = s[m.end():]
            return re.sub(r'\s+', '', s)
        assert norm(old) == norm(q.get('answer', '')), f'id={qid} 旧解析与答案不一致,跳过'
        q['explanation'] = new
        changed += 1
        print(f'  id={qid}: 解析 {len(old)}字 → {len(new)}字')
    # 保持原文件行尾 LF(与仓库一致)
    json.dump(qs, open(PATH, 'w', encoding='utf-8', newline='\n'), ensure_ascii=False, indent=1)
    print(f'完成: 共修改 {changed} 道 short 题解析 (共 {len(qs)} 题)')

if __name__ == '__main__':
    main()
